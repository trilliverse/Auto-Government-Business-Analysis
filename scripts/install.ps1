param([string]$DshHome, [switch]$Force)
. (Join-Path $PSScriptRoot 'preset-common.ps1')
$ctx = Get-GovPipelineContext -DshHome $DshHome
Assert-GovPipelineSource $ctx
# Preparation only: the running client's plugin manager owns profile installation.
$skillsPath = (Join-Path $ctx.Source 'skills').Replace('\','/')
$repoPath = $ctx.RepoRoot.Replace('\','/')
$composition = Get-Content -LiteralPath (Join-Path $ctx.Source 'agent.cordis.yml') -Raw -Encoding UTF8
$composition = $composition.Replace('__GOV_PIPELINE_SKILLS_DIR__', $skillsPath).Replace('__GOV_PIPELINE_ROOT__', $repoPath)
$metadata = Get-Content -LiteralPath (Join-Path $ctx.Source 'preset.yml') -Raw -Encoding UTF8
$patch = "# Generated by scripts/install.ps1; regenerate after moving the repository.`n- insert:`n    - id: preset-gov-pipeline`n      name: '@deepseek-ai/dsh-agent-preset'`n      config:`n        id: gov-pipeline`n        order: 20`n"
foreach ($line in ($metadata.TrimEnd() -split '\r?\n')) { $patch += "        $line`n" }
$patch += "        plugins:`n"
foreach ($line in ($composition.TrimEnd() -split '\r?\n')) { $patch += "          $line`n" }
Set-TextFileUtf8NoBom -Path (Join-Path $ctx.Source 'cordis.patch.yml') -Value $patch
Set-TextFileUtf8NoBom -Path (Join-Path $ctx.Source 'pipeline-root.txt') -Value $ctx.RepoRoot
Write-Output "Bundle 已准备：$($ctx.Source)"
Write-Output '在当前客户端的插件管理中安装上述本地目录（@local/gov-pipeline）。'
Write-Output '或由 Agent 调用 plugin_manager install_bundle，target 为该绝对目录。'
Write-Output '此脚本不再写入 .agent-presets，不更改默认预设、权限策略或业务案件。'
